// Нормализация текста для поиска. Одна и та же функция применяется к названиям позиций
// (при построении индекса) и к запросу, поэтому любые приведения работают в обе стороны.
//
// Результат — токены через один пробел, в алфавите [0-9 a-z а-я . %]:
//   «К52-1В-50В-3,3мкФ-10%»   → «к52 1в 50в 3.3мкф 10%»
//   «K52-1 50v 3.3uF» (лат.)   → «к52 1в 50в 3.3мкф»
//   «С2-33Н-0,25-10 кОм ±5%»  → «с2 33н 0.25 10к 5%»

/**
 * Латинские буквы, которые пишут вместо похожих кириллических (K52 вместо К52, 2PMT вместо
 * 2РМТ). Сравнение идёт после приведения к нижнему регистру, поэтому пары подобраны по
 * заглавным: B→В, H→Н, M→М, T→Т. Латинские названия (BZX79, SAMSUNG) при этом по-прежнему
 * находятся — они приводятся одинаково и в индексе, и в запросе.
 */
const HOMOGLYPHS: Record<string, string> = {
  a: 'а',
  b: 'в',
  c: 'с',
  e: 'е',
  h: 'н',
  k: 'к',
  m: 'м',
  o: 'о',
  p: 'р',
  t: 'т',
  x: 'х',
  y: 'у',
};

/** Латинские обозначения единиц после числа → как их пишут по-русски. */
const LATIN_UNITS: Record<string, string> = {
  uf: 'мкф',
  μf: 'мкф',
  pf: 'пф',
  nf: 'нф',
  kohm: 'к',
  kω: 'к',
  mohm: 'м',
  mω: 'м',
  ohm: 'ом',
  ω: 'ом',
  v: 'в',
  w: 'вт',
  hz: 'гц',
  khz: 'кгц',
  mhz: 'мгц',
};

// Число, затем (возможно через пробел) латинская единица, за которой не идёт буква.
const LATIN_UNIT_PATTERN = /(\d)\s*(khz|mhz|kohm|mohm|ohm|kω|mω|μf|uf|pf|nf|hz|ω|v|w)(?![a-z])/g;
// «10 кОм» → «10к», «1 МОм» → «1м», «1 ГОм» → «1г».
const KILO_OHM_PATTERN = /(\d)\s*([кмг])\s?ом(?![а-я])/g;
// Запись номиналов вида «4к7» (= 4,7 кОм) намеренно не разворачивается: в данных такие токены
// чаще означают другое — группы ТКЕ («330М1500»), контакты («2Г1»), размеры («17К45»).

/** Нормализует текст для поиска (см. описание модуля). */
export function normalizeText(input: string): string {
  let text = input.normalize('NFKC').toLowerCase().replace(/ё/g, 'е');
  // NFKC превращает микро-знак «µ» в греческую «μ»: «3.3µF» → «3.3μf».
  text = text.replace(LATIN_UNIT_PATTERN, (_, digit: string, unit: string) => {
    return digit + (LATIN_UNITS[unit] ?? unit);
  });
  text = text.replace(/[abcehkmoptxy]/g, (letter) => HOMOGLYPHS[letter] ?? letter);
  text = text.replace(/(\d),(?=\d)/g, '$1.');
  text = text.replace(KILO_OHM_PATTERN, '$1$2');
  // Всё, кроме букв, цифр, точки и процента, — разделитель.
  text = text.replace(/[^0-9a-zа-я.%]+/g, ' ');
  // Точка значима только внутри числа («0.25»), иначе она тоже разделитель («мкФ.»).
  text = text.replace(/(?<!\d)\.|\.(?!\d)/g, ' ');
  return text.replace(/\s+/g, ' ').trim();
}
