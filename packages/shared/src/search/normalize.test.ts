import { describe, expect, it } from 'vitest';
import { normalizeText } from './normalize.ts';

describe('normalizeText', () => {
  it.each([
    // Разные записи одного и того же — к одинаковому виду.
    ['К52-1В-50В-3.3мкф-10%', 'к52 1в 50в 3.3мкф 10%'],
    ['K52-1B 50V 3,3uF', 'к52 1в 50в 3.3мкф'],
    ['к52-9в-50в-33мкФ-10% (2015г.)', 'к52 9в 50в 33мкф 10% 2015г'],
    ['К50-35 2200мкФ х 63В Supertech', 'к50 35 2200мкф х 63в suреrтесн'],
    ['3.3µF 16v', '3.3мкф 16в'],
    // Резисторы: кОм/МОм → к/м.
    ['С2-33Н-0,25-10 кОм ±5%', 'с2 33н 0.25 10к 5%'],
    ['С2-33 1,5КОм', 'с2 33 1.5к'],
    ['ПЭВ 10 56 ОМ 10%', 'пэв 10 56 ом 10%'],
    ['5.1 МОм', '5.1м'],
    // «4к7» и «330М1500» не трогаем: второе — группа ТКЕ, а не номинал.
    ['МЛТ-0,25 4к7', 'млт 0.25 4к7'],
    ['К10-17А-330М1500 10%', 'к10 17а 330м1500 10%'],
    ['10 КОМПЛЕКТ', '10 комплект'],
    // Гомоглифы в смешанных токенах из файла.
    ['2PМТ22КУЭ4Г3В1В', '2рмт22куэ4г3в1в'],
    ['MПО', 'мпо'],
    ['KT315', 'кт315'],
    // Разделители и мусор.
    ['ОНЦ-БС-2-19/18-Р12-3В', 'онц бс 2 19 18 р12 3в'],
    ['140УД17А ВК зол.', '140уд17а вк зол'],
    ['К10-17а-50В-МП0-16пФ-5%-В в/р1', 'к10 17а 50в мп0 16пф 5% в в р1'],
    ['Ёмкость', 'емкость'],
    ['...', ''],
  ])('«%s» → «%s»', (input, expected) => {
    expect(normalizeText(input)).toBe(expected);
  });

  it('одинаково приводит запрос латиницей и название кириллицей', () => {
    expect(normalizeText('K52-1 50в')).toBe(normalizeText('К52-1 50В'));
    expect(normalizeText('2PMT22')).toBe(normalizeText('2РМТ22'));
  });
});
